// Regenerates the logo PNGs, email logo and Open Graph image from SVG. Outputs are committed; run only after changes.
import sharp from "sharp";
import { readFileSync, writeFileSync } from "node:fs";

const logo = readFileSync("public/rfp-logo.svg");
await sharp(logo, { density: 200 }).resize(825).png().toFile("public/rfp-logo.png");
const small = await sharp(logo, { density: 200 }).resize(160).png({ compressionLevel: 9 }).toBuffer();
writeFileSync(
  "lib/emailLogo.ts",
  `// The Reserve Fund Plans logo, embedded in the enquiry email so it always shows. Generated by scripts/make-assets.mjs.\nexport const EMAIL_LOGO_CID = "rfp-logo";\nexport const EMAIL_LOGO_BASE64 =\n  "${small.toString("base64")}";\n`,
);

const diamonds = `<g transform="translate(905 120) scale(2.6)"><path d="M42.5 4.5 58 25 42.5 45.5 27 25Z" fill="#3F57A2"/><path d="M59.5 27.5 75 48 59.5 68.5 44 48Z" fill="#E7C733"/><path d="M42.5 50.5 58 71 42.5 91.5 27 71Z" fill="#CC222E"/><path d="M25.5 27.5 41 48 25.5 68.5 10 48Z" fill="#599B51"/></g>`;
const logoInner = logo.toString().replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
const og = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630">
  <rect width="1200" height="630" fill="#f6f6f4"/>
  <g transform="translate(80 70) scale(0.36)">${logoInner}</g>
  <text x="80" y="330" font-family="Plus Jakarta Sans, Arial, sans-serif" font-weight="800" font-size="60" fill="#171717" letter-spacing="-1.5">10 Year Reserve Fund Plans</text>
  <text x="80" y="410" font-family="Plus Jakarta Sans, Arial, sans-serif" font-weight="800" font-size="60" fill="#c8331a" letter-spacing="-1.5">&amp; Strata Reports, WA</text>
  <text x="80" y="490" font-family="Plus Jakarta Sans, Arial, sans-serif" font-weight="500" font-size="28" fill="#474747">Insurance valuations · WHS reports · Asbestos reports · Since 1984</text>
  <rect x="0" y="590" width="1200" height="40" fill="#141414"/>
  <text x="80" y="617" font-family="Plus Jakarta Sans, Arial, sans-serif" font-weight="700" font-size="20" fill="#f5dc3c">1300 55 18 30 · reservefundplans.com.au</text>
  ${diamonds}
</svg>`;
await sharp(Buffer.from(og)).png().toFile("public/og-image.png");
console.log("assets written");
